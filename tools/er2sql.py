#!/usr/bin/env python3
"""Generates the school-app-server Flyway migrations V2 (tables), V3 (foreign keys) and V4 (tenant guards)
from tools/er_v5_school.dsl. V1 (schemas, roles, directory cache) is hand-written.

Run once per ER revision:  python3 tools/er2sql.py tools/er_v5_school.dsl src/main/resources/db/migration
After a migration has been applied anywhere, never regenerate it: write a new V<n> by hand instead.
"""
import re
import sys
from collections import OrderedDict

TYPES = {"i": "INTEGER", "b": "BIGINT", "s": "TEXT", "d": "DATE", "dt": "TIMESTAMPTZ", "tm": "TIME",
         "n": "NUMERIC(14,2)", "f": "DOUBLE PRECISION", "bo": "BOOLEAN", "j": "JSONB", "a": "TEXT[]", "u": "UUID"}

# Append-only ledgers (Schema v5): UPDATE / DELETE raise
LEDGERS = ["custody.event", "finance.wallet_txn", "finance.payment_allocation", "accounts.petty_cash_txn",
           "operations.attendance_punch", "compliance.consent_record", "inventory.inventory_transaction",
           "hostel.outing_movement", "security.patrol_scan", "platform.flow_transition_log", "audit.audit_log"]


def q(name):
    return '"' + name + '"'


def qt(table):
    s, t = table.split(".")
    return q(s) + "." + q(t)


class Column:
    def __init__(self, line):
        parts = line.split()
        self.name, self.code = parts[0], parts[1]
        self.pk = self.pkc = self.nn = False
        self.uk = None
        self.fk = None
        self.enum = None
        self.default = None
        for p in parts[2:]:
            if p == "pk":
                self.pk = True
            elif p == "pkc":
                self.pkc = True
            elif p == "nn":
                self.nn = True
            elif p == "uk":
                self.uk = []
            elif p.startswith("uk:"):
                self.uk = p[3:].split(",")
            elif p.startswith(">"):
                self.fk = p[1:]
            elif p.startswith("{"):
                self.enum = p.strip("{}").split("|")
            elif p.startswith("="):
                self.default = p[1:]
            else:
                raise ValueError("unknown flag %r in %r" % (p, line))

    @property
    def sql_type(self):
        if self.name.endswith("_id") and self.code in ("i", "b"):
            return "BIGINT"
        return TYPES[self.code]

    def ddl(self):
        out = q(self.name) + " " + self.sql_type
        if self.pk:
            out += " GENERATED BY DEFAULT AS IDENTITY"
        if self.pk or self.pkc or self.nn:
            out += " NOT NULL"
        d = self.default
        if d is None and self.name == "status" and self.enum and self.nn:
            d = self.enum[0]
        if d is not None:
            if d == "now()":
                out += " DEFAULT now()"
            elif d == "now()+30d":
                out += " DEFAULT (now() + INTERVAL '30 days')"
            elif d in ("true", "false") or re.fullmatch(r"-?\d+(\.\d+)?", d):
                out += " DEFAULT " + d
            else:
                out += " DEFAULT '" + d + "'"
        if self.enum:
            out += " CHECK (%s IN (%s))" % (q(self.name), ", ".join("'%s'" % e for e in self.enum))
        return out


class Table:
    def __init__(self, header):
        bits = header.split()
        self.name = bits[0]
        self.schema, self.short = self.name.split(".")
        self.added = "+" in bits
        self.nullable_tenant = "?tenant" in bits
        self.columns = []
        self.keys = []      # UNIQUE NULLS NOT DISTINCT
        self.uniques = []
        self.pk_school = False

    @property
    def pk(self):
        return next((c for c in self.columns if c.pk), None)

    def constraint(self, suffix):
        name = "%s_%s_%s" % (self.schema, self.short, suffix)
        return name[:63]


def parse(path):
    tables = OrderedDict()
    cur = None
    for raw in open(path):
        line = raw.split("#", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        line = line.strip()
        if line.startswith("== "):
            cur = Table(line[3:])
            if cur.name in tables:
                raise ValueError("duplicate table " + cur.name)
            tables[cur.name] = cur
        elif line.startswith("@key("):
            cur.keys.append(line[5:-1].split(","))
        elif line.startswith("@unique("):
            cur.uniques.append(line[8:-1].split(","))
        elif line == "@pkschool":
            cur.pk_school = True
        else:
            cur.columns.append(Column(line))
    # validate FK targets
    for t in tables.values():
        for c in t.columns:
            if c.fk and c.fk != "U":
                if c.fk not in tables:
                    raise ValueError("%s.%s -> unknown %s" % (t.name, c.name, c.fk))
                target = tables[c.fk]
                if not target.pk:
                    raise ValueError("%s.%s -> %s has no identity pk" % (t.name, c.name, c.fk))
    return tables


def gen_tables(tables):
    out = ["-- =============================================================================",
           "-- school-app-server V2 — all tenant tables of ER v5 (school DB).",
           "-- GENERATED by tools/er2sql.py from tools/er_v5_school.dsl; do not edit (write a new migration).",
           "-- Every table carries school_id (the auth-issued branch id) and UNIQUE (school_id, <pk>) so that",
           "-- other tables can reference it with a composite (school_id, x_id) key (V3).",
           "-- ============================================================================="]
    schema = None
    for t in tables.values():
        if t.schema != schema:
            schema = t.schema
            out.append("\n-- " + "-" * 75 + "\n-- " + schema + "\n-- " + "-" * 75)
        cols = []
        school = '"school_id" BIGINT' + ("" if t.nullable_tenant else " NOT NULL")
        cols.append(school)
        for c in t.columns:
            cols.append(c.ddl())
        cons = []
        pkc = [c.name for c in t.columns if c.pkc]
        if t.pk:
            cons.append("CONSTRAINT %s PRIMARY KEY (%s)" % (q(t.constraint("pkey")), q(t.pk.name)))
            if not t.nullable_tenant:
                cons.append("CONSTRAINT %s UNIQUE (\"school_id\", %s)" % (q(t.constraint("tenant_key")), q(t.pk.name)))
        elif pkc:
            cons.append("CONSTRAINT %s PRIMARY KEY (\"school_id\", %s)" % (q(t.constraint("pkey")), ", ".join(map(q, pkc))))
        elif t.pk_school:
            cons.append("CONSTRAINT %s PRIMARY KEY (\"school_id\")" % q(t.constraint("pkey")))
        for c in t.columns:
            if c.uk is not None:
                cols_ = ["school_id"] + c.uk + [c.name]
                cons.append("CONSTRAINT %s UNIQUE (%s)" % (q(t.constraint(c.name + "_key")), ", ".join(map(q, cols_))))
        for i, u in enumerate(t.uniques):
            cons.append("CONSTRAINT %s UNIQUE (%s)" % (q(t.constraint("uq%d" % (i + 1))), ", ".join(map(q, ["school_id"] + u))))
        for i, k in enumerate(t.keys):
            cons.append("CONSTRAINT %s UNIQUE NULLS NOT DISTINCT (%s)" % (q(t.constraint("key%d" % (i + 1))),
                                                                       ", ".join(map(q, ["school_id"] + k))))
        tag = "  -- addition beyond ER v5" if t.added else ""
        if t.nullable_tenant:
            tag += "  -- school_id NULL = platform default row"
        out.append("\nCREATE TABLE %s (%s\n    %s\n);" % (qt(t.name), tag, ",\n    ".join(cols + cons)))
    return "\n".join(out) + "\n"


def gen_fks(tables):
    out = ["-- =============================================================================",
           "-- school-app-server V3 — foreign keys and their indexes.",
           "-- GENERATED by tools/er2sql.py; do not edit.",
           "-- References to tenant data are composite (school_id, x_id): a row can never point at another branch.",
           "-- References to users are single-column to directory.app_user (the auth user id).",
           "-- ============================================================================="]
    n = 0
    for t in tables.values():
        out.append("\n-- " + t.name)
        out.append("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (\"school_id\") REFERENCES \"directory\".\"school\" (\"school_id\");"
                   % (qt(t.name), q(t.constraint("school_fk"))))
        out.append("CREATE INDEX %s ON %s (\"school_id\");" % (q(t.constraint("school_idx")), qt(t.name)))
        for c in t.columns:
            if not c.fk:
                continue
            n += 1
            cname = q(t.constraint(c.name + "_fk"))
            if c.fk == "U":
                out.append("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES \"directory\".\"app_user\" (\"user_id\");"
                           % (qt(t.name), cname, q(c.name)))
                if not (c.pkc and t.columns.index(c) == 0):
                    out.append("CREATE INDEX %s ON %s (%s);" % (q(t.constraint(c.name + "_idx")), qt(t.name), q(c.name)))
            else:
                target = tables[c.fk]
                if target.nullable_tenant:
                    # rows may reference platform-default rows (school_id NULL), so the key is single-column
                    out.append("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s);"
                               % (qt(t.name), cname, q(c.name), qt(target.name), q(target.pk.name)))
                else:
                    out.append("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (\"school_id\", %s) REFERENCES %s (\"school_id\", %s);"
                               % (qt(t.name), cname, q(c.name), qt(target.name), q(target.pk.name)))
                out.append("CREATE INDEX %s ON %s (\"school_id\", %s);" % (q(t.constraint(c.name + "_idx")), qt(t.name), q(c.name)))
    out.append("\n-- %d foreign keys" % n)
    return "\n".join(out) + "\n"


def gen_guards(tables):
    out = ["-- =============================================================================",
           "-- school-app-server V4 — tenant guards: row-level security on every tenant table, grants for the",
           "-- application role, append-only ledgers, and a few cross-row rules.",
           "-- GENERATED by tools/er2sql.py; do not edit.",
           "--",
           "-- platform-core runs, inside every transaction:",
           "--   SET LOCAL app.school_ids = '12,13'   (token school_access ∩ X-School-Id)",
           "--   SET LOCAL app.user_id    = '42'",
           "--   SET LOCAL app.org_ids    = '7'       (org-wide reports only)",
           "-- No context = no rows. Background jobs set app.rls_bypass = 'on'.",
           "-- The app must connect as a member of schoolcrm_app (not the Flyway owner), or RLS is skipped.",
           "-- ============================================================================="]
    for t in tables.values():
        out.append("\nALTER TABLE %s ENABLE ROW LEVEL SECURITY;" % qt(t.name))
        if t.nullable_tenant:
            read = "\"school_id\" IS NULL OR \"school_id\" = ANY (platform.current_school_ids()) OR platform.rls_bypass()"
            if t.name == "platform.saved_report":
                read += " OR (\"school_id\" IS NULL AND \"organization_id\" = ANY (platform.current_org_ids()))"
            out.append("CREATE POLICY tenant_read ON %s FOR SELECT USING (%s);" % (qt(t.name), read))
            out.append("CREATE POLICY tenant_write ON %s FOR ALL USING (\"school_id\" = ANY (platform.current_school_ids()) OR platform.rls_bypass())\n"
                       "    WITH CHECK (\"school_id\" = ANY (platform.current_school_ids()) OR platform.rls_bypass());" % qt(t.name))
        else:
            out.append("CREATE POLICY tenant_isolation ON %s USING (\"school_id\" = ANY (platform.current_school_ids()) OR platform.rls_bypass())\n"
                       "    WITH CHECK (\"school_id\" = ANY (platform.current_school_ids()) OR platform.rls_bypass());" % qt(t.name))
    schemas = sorted({t.schema for t in tables.values()})
    out.append("\n-- Grants: the application role reads and writes tenant tables (RLS decides which rows)")
    for s in schemas:
        out.append("GRANT USAGE ON SCHEMA %s TO schoolcrm_app;" % q(s))
        out.append("GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA %s TO schoolcrm_app;" % q(s))
        out.append("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA %s TO schoolcrm_app;" % q(s))
    out.append("REVOKE UPDATE, DELETE ON \"audit\".\"audit_log\" FROM schoolcrm_app;")

    out.append("\n-- Append-only ledgers")
    out.append("""CREATE OR REPLACE FUNCTION platform.refuse_ledger_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only; record a correcting entry instead', TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME
        USING ERRCODE = 'insufficient_privilege';
END $$;""")
    for name in LEDGERS:
        if name in tables:
            out.append("CREATE TRIGGER trg_append_only BEFORE UPDATE OR DELETE ON %s FOR EACH ROW EXECUTE FUNCTION platform.refuse_ledger_change();" % qt(name))

    out.append("""
-- One current academic year per branch
CREATE UNIQUE INDEX academics_academic_year_one_current ON "academics"."academic_year" ("school_id") WHERE "is_current";

-- One ACTIVE bed per student and one ACTIVE student per bed
CREATE UNIQUE INDEX hostel_allocation_one_active_student ON "hostel"."allocation" ("school_id", "student_id") WHERE "status" = 'ACTIVE';
CREATE UNIQUE INDEX hostel_allocation_one_active_bed ON "hostel"."allocation" ("school_id", "bed_id") WHERE "status" = 'ACTIVE';

-- One active chief warden per hostel
CREATE UNIQUE INDEX hostel_staff_assignment_one_chief ON "hostel"."staff_assignment" ("school_id", "hostel_id")
    WHERE "duty" = 'CHIEF_WARDEN' AND "to_date" IS NULL;

-- Approver is never the submitter (four-eyes) for presence corrections and staff leave
ALTER TABLE "operations"."daily_presence" ADD CONSTRAINT operations_daily_presence_not_self
    CHECK ("person_kind" <> 'STAFF' OR "corrected_by_user_id" IS DISTINCT FROM "person_id");
ALTER TABLE "hr"."leave_request" ADD CONSTRAINT hr_leave_request_not_self
    CHECK ("approver_user_id" IS DISTINCT FROM "user_id");
ALTER TABLE "operations"."attendance_punch" ADD CONSTRAINT operations_attendance_punch_manual_by_other
    CHECK ("source" <> 'MANUAL' OR ("marked_by_user_id" IS NOT NULL AND ("person_kind" <> 'STAFF' OR "marked_by_user_id" <> "person_id")));

-- Feed query: live posts only (expires_at = created_at + 30 days)
CREATE INDEX communication_news_post_live ON "communication"."news_post" ("school_id", "created_at" DESC)
    WHERE "deleted_at" IS NULL;

-- Never store more than the last 4 digits of Aadhaar
ALTER TABLE "academics"."student" ADD CONSTRAINT academics_student_aadhaar_last4
    CHECK ("aadhaar_last4" IS NULL OR "aadhaar_last4" ~ '^[0-9]{4}$');

-- Outbox polling
CREATE INDEX platform_outbox_event_pending ON "platform"."outbox_event" ("next_attempt_at") WHERE "status" = 'PENDING';
""")
    return "\n".join(out) + "\n"


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    tables = parse(src)
    open(outdir + "/V2__domain_tables.sql", "w").write(gen_tables(tables))
    open(outdir + "/V3__foreign_keys.sql", "w").write(gen_fks(tables))
    open(outdir + "/V4__tenant_guards_rls.sql", "w").write(gen_guards(tables))
    schemas = OrderedDict()
    for t in tables.values():
        schemas.setdefault(t.schema, 0)
        schemas[t.schema] += 1
    print("%d tables in %d schemas: %s" % (len(tables), len(schemas),
                                           ", ".join("%s %d" % kv for kv in schemas.items())), file=sys.stderr)
    print(" ".join(sorted(schemas)), file=sys.stderr)


if __name__ == "__main__":
    main()
