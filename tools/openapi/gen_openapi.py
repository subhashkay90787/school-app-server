#!/usr/bin/env python3
"""Generates the school-app-server API contracts:

  src/main/resources/openapi/<actor>.yaml   one spec per actor (Java interfaces in com.school.app.role.<actor>.api)
  src/main/resources/openapi/school-app-api.yaml   all actors in one file (docs, Dart client for the Flutter app)
  src/main/resources/openapi/role-routes.json      /api/v1/<actor> -> base roles allowed (read by platform-core)

Usage: python3 tools/openapi/gen_openapi.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import yaml  # noqa: E402
import actors as actor_defs  # noqa: E402
import views  # noqa: E402
from spec import Registry, build_spec  # noqa: E402

VERSION = "1.0.0"
OUT = os.path.join(ROOT, "src/main/resources/openapi")


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def _od(dumper, data):
    return dumper.represent_dict(data.items())


from collections import OrderedDict  # noqa: E402
Dumper.add_representer(OrderedDict, _od)


def dump(spec, path):
    with open(path, "w") as f:
        f.write("# GENERATED by tools/openapi/gen_openapi.py from tools/er_v5_school.dsl and tools/openapi/*.py\n")
        f.write("# Edit the generator, not this file.\n")
        yaml.dump(spec, f, Dumper=Dumper, sort_keys=False, width=120, allow_unicode=True)


def main():
    reg = Registry(os.path.join(ROOT, "tools/er_v5_school.dsl"))
    views.define(reg)
    actors = actor_defs.build(reg)
    os.makedirs(OUT, exist_ok=True)
    total = 0
    routes = {}
    op_ids = set()
    for a in actors:
        spec = build_spec(reg, [a], "SchoolCRM app server: %s API" % a.title, VERSION,
                          a.description + "\n\nBase path /api/v1/%s. Base roles: %s. Every request needs a school-auth "
                          "access token and X-School-Id (except /common/me)." % (a.key, ", ".join(a.base_roles)), "/")
        dump(spec, os.path.join(OUT, a.key + ".yaml"))
        routes["/api/v1/" + a.key] = a.base_roles
        total += len(a.ops)
        for o in a.ops:
            key = (a.key, o["op_id"])
            if key in op_ids:
                raise ValueError("duplicate operationId %s" % (key,))
            op_ids.add(key)
        print("%-20s %3d operations, %3d schemas" % (a.key, len(a.ops), len(spec["components"]["schemas"])), file=sys.stderr)
    bundle = build_spec(reg, actors, "SchoolCRM app server API (all actors)", VERSION,
                        "All actor APIs of school-app-server in one document (tags = actors). Same paths as the "
                        "per-actor specs; operationIds are prefixed with the actor key.", "/", prefix_ids=True)
    dump(bundle, os.path.join(OUT, "school-app-api.yaml"))
    with open(os.path.join(OUT, "role-routes.json"), "w") as f:
        json.dump(routes, f, indent=2)
    print("total %d operations, %d schemas in the bundle" % (total, len(bundle["components"]["schemas"])), file=sys.stderr)


if __name__ == "__main__":
    main()
